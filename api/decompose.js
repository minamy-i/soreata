const EXAMPLES = `【例：「太郎くんのうしろに並んで」の指示に従わせる】

## 太郎くんの顔がわかる
「太郎くん」の特定に顔の識別が前提になっている。顔を見分ける力は全員が持つわけではない。
対応：名前カードや帽子の色など、顔以外の手がかりを用意する。

## 太郎くんのうしろがわかる
「うしろ」は太郎くんの身体を基準にした位置であり、自分視点の空間理解だけでは足りない。
対応：足跡マークや矢印など、「うしろ」の位置を視覚的に示す。

## 指示の言葉を理解できる
「太郎くんの」「うしろに」「並んで」の言葉を聞き取り、意味を結びつける処理が前提になっている。
対応：写真・絵・文字カードを加え、言葉以外でも意味が伝わるようにする。

## 三つの手順を同時にこなせる
「太郎くんを特定する」「うしろを見つける」「並ぶ」の同時処理が必要になる。一つずつは分かっても統合が難しい場合がある。
対応：「まず太郎くんを見つけて」「次にうしろへ」と段階的に伝える。

## 並んでいる様子を見て真似できる
周囲の子が並ぶ様子を見て、自分もそこへ行けばよいと判断する力が使われる。言語理解の代替ルートになる。
対応：先生や友達が実際に並ぶ姿を見せ、視覚的な手本を提供する。

## 並び方を知っている
「並ぶ」には向き・順番・適度な間隔を守るという暗黙ルールが含まれている。「適度」がどのくらいかも自明ではない。
対応：床に足跡マークを貼るなど、位置と間隔を視覚的に示す。

【例：「大玉送り」で相手チームの邪魔に行かないようにする】

## 相手チームを邪魔しないルールを知っている
競争を理解し勝とうとしていたが、「相手チームの人や玉には触らない」という暗黙ルールだけが欠けていた。
対応：「相手チームの人や玉には触らない」と言葉にして事前に伝える。

## エリアの境界がわかる
自分たちのエリアと相手のエリアが空間的に分かれているという理解が前提になっている。これが曖昧だと移動が自然な行動になる。
対応：ラインやコーンで境界を視覚的に示す。

## 相手チーム側から自分の行動が想像できる
「邪魔している」と気づくには相手チームの立場から自分の行動を見る必要がある。自分視点では合理的な行動にしか見えない。
対応：「相手の立場ならどうか」を絵や言葉で具体的に示す。

## 邪魔すると反則になるとわかっている
邪魔に行くことで反則になるという連鎖を予測する必要がある。目の前の行動と先の結果がつながっていない場合、止まる理由が見えない。
対応：「こうすると次にこうなる」という流れを事前に伝える。

## 興奮してもルール内で動ける
競争の盛り上がりの中では興奮が判断より先に行動を引き起こすことがある。これは意志の弱さではなく、感情が先に行動を引き起こしてしまうことがある。
対応：興奮しやすい場面の前に、やっていいこと・いけないことを確認しておく。

【例：走り回る2歳児を部屋前方の紙芝居に注目させる】

## 走り回らないでいられる
身体を動かすことで足りない感覚を補おうとしていることがある。この欲求が満たされないまま静止を求めても効果はない。
対応：抱っこして揺らすなど、身体を動かしたい感覚を満たしながら注目を促す。

## 紙芝居に注目できる
部屋の刺激がすべて等価に飛び込む中で、紙芝居という一点に注意を絞る処理が必要になる。
対応：余分な刺激を減らすか、紙芝居自体を声や動きで際立たせる。

## 静止し続けられる
静止すると身体の位置や動きの感覚がつかみにくくなり、不安感が生じることがある。走ることでその感覚を補おうとしていることがある。
対応：振動クッションや重みのあるベストなど、身体の位置や動きの感覚を補う。

## 紙芝居を見続けられる
紙芝居への注意を維持するには外からの刺激を抑えながら内側の関心を保つ必要がある。2歳児ではまだ難しいことがある。
対応：短い場面ごとに区切り、名前を呼んで注意を引き戻す工夫を繰り返す。

## 指示にある言葉を理解できる
「こっちを見て」などの言葉を聞いて意味に変え、行動に結びつける処理が前提になっている。この処理が難しいと、口頭指示が届かないことがある。
対応：身振り・指さし・実演を加え、言葉以外でも指示が伝わるようにする。

## 周りの様子を手がかりにできる
周囲が紙芝居を見ているという状況を自分の行動の手がかりにする力が必要になる。周りを見て自分の動きを調整する力は、まだ難しいことがある。
対応：大人が先に紙芝居に熱中する姿を見せ、感情を共有することで注視を促す。`;

// 課題テキストからGeminiに送るプロンプトを組み立てる
function buildPrompt(task) {
    return `あなたは、「できて当たり前」とされる課題が人に何を要求するかを分析する研究者です。
行動の良し悪しではなく、その課題を可能にする認知・感覚・社会的認知・運動の前提条件を特定します。

【分解の原則】
- 人・物・動作・空間・時間・知識の6つの観点で課題を掘る（この観点はユーザには見せない）
- 隠れた要素は別要素の内側に折り畳まれている。一段で止めず再分解する
- できる人が通る経路を必須条件と混同しない。経路は一本ではない
- 対処や代替が考えられる深さまで掘る。それ以上は掘らない
- 暗黙のルールや前提知識が関係する場合は必ず含める

${EXAMPLES}

【課題】
${task}

この課題が要求する人に必要な能力まで分解する。
各能力に対して、本人や周囲の人が無理なくできる代替手段をまとめて「対応：」として提案する。
対応は、本人が感覚・認知・社会的な欲求を満たすことを目的とする。行動を止める・制御することを目的としない。
「できない」は意欲や努力、育て方の問題ではなく、前提となる能力の話であることを文中で示す。

【出力形式】厳守
以下の形式のみで出力すること。前置き・総括・まとめは一切書かない。
各能力を「## タイトル」の見出しで始め、その後に分解と対応を書く。
タイトルは、課題文の中の単語を使い、極力簡潔な肯定文にまとめる。専門語・学術語は使わない。
各能力の分解と対応を合わせて250字以内にする。`;
}

module.exports = async (req, res) => {
    if (req.method !== 'POST') {
        return res.status(405).json({ error: 'Method Not Allowed' });
    }

    const { task } = req.body;
    if (!task) {
        return res.status(400).json({ error: '課題が入力されていません' });
    }

    const apiKey = process.env.GEMINI_API_KEY;
    const url = `https://generativelanguage.googleapis.com/v1beta/models/gemini-3.1-flash-lite:generateContent?key=${apiKey}`;

    try {
        const response = await fetch(url, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({
                contents: [{ parts: [{ text: buildPrompt(task) }] }]
            })
        });

        const data = await response.json();

        if (!response.ok) {
            return res.status(response.status).json({ error: data.error?.message || 'Gemini APIエラー' });
        }

        const result = data.candidates?.[0]?.content?.parts?.[0]?.text;
        if (!result) {
            return res.status(500).json({ error: '出力が取得できませんでした' });
        }

        return res.status(200).json({ result });

    } catch (err) {
        return res.status(500).json({ error: '通信エラーが発生しました' });
    }
};
